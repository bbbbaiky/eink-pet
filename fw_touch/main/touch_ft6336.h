/* ============================================================================
 * touch_ft6336.h —— 触屏版（ESP32-S3-Touch-ePaper-1.54，SKU 34211）FT6336 触摸驱动
 *
 * 里程碑 1（2026-10-04）：极简轮询版 —— 不用 INT，20ms 轮询读点数+坐标。
 *   目的：先把「屏 + 触摸」硬件通路打通（串口打点日志），页面流后面接。
 *
 * 引脚（官方 1.54 系列文档 / 1.54G 引脚表推断，里程碑 1 串口验证）：
 *   I2C SDA=47 / SCL=48（板上共享 I2C，触屏版固件独占使用）
 *   TP_RST=7 / TP_INT=21（INT 本驱动暂不使用，只配成输入）
 *   ⚠ 若串口看到「FT6336 无应答」，第一嫌疑就是这组引脚，对照官方例程改。
 *
 * FT6336 协议要点（FocalTech 通用）：
 *   7 位地址 0x38；寄存器 0x02 = TD_STATUS（低 4 位 = 触摸点数，0 或 >4 无效）；
 *   每点 6 字节自 0x03 起：XH XL YH YL WEIGHT MISC；
 *   XH bit3:0 = X 高 4 位，YH bit3:0 = Y 高 4 位（bit7:6 是事件类型，此处不关心）。
 * ==========================================================================*/
#pragma once
#include <stdbool.h>
#include <stdint.h>

/* 初始化 I2C + 复位触摸 IC。返回 0 = 成功（能读到版本寄存器 0xA8 非零）。
 * 失败时把 err 打进日志并返回 -1 —— 里程碑 1 允许失败，别 panic。 */
int tp_init(void);

/* 轮询一次。有触摸点 → 返回 1 并填 *x,*y（**原始报告值**，映射由调用方做）；
 * 无触摸 → 返回 0；I2C 出错 → 返回 -1（调用方按无触摸处理并限频打日志）。 */
int tp_poll(int *x, int *y);
