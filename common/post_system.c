/* 条目时间戳（统一编码：内置槽 k≥0 查 s_mp_ts；卡信 e<0 查 s_sd[]）。 */
uint32_t mypost_entry_ts(int e)
{
    if (e >= 0) return (e < MYPOST_MAX) ? s_mp_ts[e] : 0;
    int i = -2 - e;
    return (i >= 0 && i < s_sd_n) ? s_sd[i] : 0;
}

static bool mypost_before(int a, int b)
{
    const uint32_t ta = mypost_entry_ts(a), tb = mypost_entry_ts(b);
    if (ta != tb) return ta > tb;
    const int pa = (a >= 0) ? a : (MYPOST_MAX + (-2 - a));
    const int pb = (b >= 0) ? b : (MYPOST_MAX + (-2 - b));
    return pa < pb;
}

/* ★R147 修 P1：卡信编码原本是 e = -1-i，与「-1 = 这一位次不存在」的返回值撞车 ——
   只要卡上有转存信，best 变负就被下面 `if (best < 0) return -1` 判成「找不到」，
   于是「特殊信件」列表首行就 break（整页空白）、详情页画空态、删除变空操作。
   现在卡信编码改到 **e = -2-i**（-1 只表示不存在），best 的 -1 哨兵恢复单义。 */
int mypost_rank_entry(int rank)
{
    if (rank < 0) return -1;
    int  last = -1;
    bool have = false;
    for (int it = 0; it <= rank; ++it) {
        int best = -1;
        for (int k = 0; k < MYPOST_MAX; ++k) {
            if (!s_mp_ts[k]) continue;
            if (have && !mypost_before(last, k)) continue;
            if (best < 0 || mypost_before(k, best)) best = k;
        }
        for (int i = 0; i < s_sd_n; ++i) {
            if (!s_sd[i]) continue;
            const int e = -2 - i;
            if (have && !mypost_before(last, e)) continue;
            if (best < 0 || mypost_before(e, best)) best = e;
        }
        if (best < 0) return -1;
        last = best;
        have = true;
    }
    return last;
}

/* 条目在显示序中的位次（0-based）；条目不存在 = -1。 */
int mypost_entry_rank(int e)
{
    if (e >= 0) { if (e >= MYPOST_MAX || !s_mp_ts[e]) return -1; }
    else        { const int i = -2 - e; if (i < 0 || i >= s_sd_n || !s_sd[i]) return -1; }
    int r = 0;
    for (int k = 0; k < MYPOST_MAX; ++k)
        if (s_mp_ts[k] && mypost_before(k, e)) ++r;
    for (int i = 0; i < s_sd_n; ++i)
        if (s_sd[i] && mypost_before(-2 - i, e)) ++r;
    return r;
}

/* 按 ts 反查条目（同 ts 取显示序最靠前的一条）；不存在 = -1。 */
int mypost_entry_by_ts(uint32_t ts)
{
    if (!ts) return -1;
    int best = -1;
    for (int k = 0; k < MYPOST_MAX; ++k)
        if (s_mp_ts[k] == ts && (best < 0 || mypost_before(k, best))) best = k;
    for (int i = 0; i < s_sd_n; ++i)
        if (s_sd[i] == ts && (best < 0 || mypost_before(-2 - i, best))) best = -2 - i;
    return best;
}

