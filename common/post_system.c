/* 算 mypost 区偏移；分区够大才 true */
bool mypost_layout(void)
{
    const esp_partition_t *p = assets_part();
    if (!p) return false;
    if (p->size <= MYPOST_SIZE + 0x10000u) return false;   /* 至少给内置留 64KB */
    s_mp_off = p->size - MYPOST_SIZE;
    return true;
}

/* 读槽元数据 → 有效? + ts（无效/损坏返回 false）*/
static bool mypost_slot_get(int k, uint32_t *ts)
{
    uint8_t meta[16];
    if (!assets_read(s_mp_off + MYPOST_SLOT_OFF + (uint32_t)k * MYPOST_SLOT_SZ + MYPOST_META_OFF,
                     meta, sizeof(meta)))
        return false;
    if (a_rd32(meta) != MYPOST_SLOT_MAGIC) return false;
    if (ts) *ts = a_rd32(meta + 4);
    return true;
}

/* 开机装载：算偏移 + 校验/初始化 header + 扫描槽建索引。非致命。 */
void mypost_load(void)
{
    if (!s_mp_mux) s_mp_mux = xSemaphoreCreateMutex();   /* ★R119：开机单任务创建 */
    if (!mypost_layout()) { ESP_LOGW(TAG, "mypost: 分区过小/缺失，功能禁用"); return; }

    uint8_t hdr[16] = {0};
    bool inited = assets_read(s_mp_off + MYPOST_HDR_OFF, hdr, sizeof(hdr)) &&
                  a_rd32(hdr) == MYPOST_MAGIC;
    if (!inited) {
        /* 首次使用/损坏：擦 header 扇区 → 写 magic/ver（数据槽保持擦除态=全空）*/
        if (!assets_erase(s_mp_off + MYPOST_HDR_OFF, 0x1000)) {
            ESP_LOGW(TAG, "mypost: 擦 header 失败，功能禁用"); return;
        }
        uint8_t w[16] = {0};
        w[0]=(uint8_t)MYPOST_MAGIC;       w[1]=(uint8_t)(MYPOST_MAGIC>>8);
        w[2]=(uint8_t)(MYPOST_MAGIC>>16); w[3]=(uint8_t)(MYPOST_MAGIC>>24);
        w[4]=(uint8_t)MYPOST_VER;         w[5]=(uint8_t)(MYPOST_VER>>8);
        w[6]=(uint8_t)(MYPOST_VER>>16);   w[7]=(uint8_t)(MYPOST_VER>>24);
        if (!assets_write(s_mp_off + MYPOST_HDR_OFF, w, sizeof(w))) {
            ESP_LOGW(TAG, "mypost: 写 header 失败，功能禁用"); return;
        }
        ESP_LOGI(TAG, "mypost: 首次初始化（%u B @ assets+0x%X）", MYPOST_SIZE, (unsigned)s_mp_off);
    }
    /* ★★★ 2026-10-22 扩容 99→200 槽的**免迁移**原理（实测证实，改动前务必读懂）：
       旧区 = [尾-400K, 尾)，新区 = [尾-804K, 尾) —— 旧区整体位于新区**后半段**，
       二者都 4KB 对齐 ⇒ 旧槽 k 的起点 = 尾-400K+4K+k×4K，恰好落在新区槽 (k+101) 的起点上
       （0x34D000 − 0x2E8000 = 404KB = 101 槽）。**老卡数据自动在位，一张不少**
       —— 实测：触屏版升级后日志「已存 1/200」，卡照常能看。
       ⚠ 因此**不要**写"旧槽→新槽"的搬运代码：那会把同一张卡复制成两张。
       ⚠ 旧区 header（= 新区槽 100 的起点偏移 0）残留的 MYPOST_MAGIC 不会被当卡片
          （槽有效判据看的是 meta 偏移 2560 处的 "MYPC"），且将来写卡前会整槽 erase。 */
    int cnt = 0;
    for (int k = 0; k < MYPOST_MAX; ++k) {
        uint32_t ts = 0;
        if (mypost_slot_get(k, &ts)) { s_mp_ts[k] = ts; cnt++; }
        else s_mp_ts[k] = 0;
    }
    s_mp_ready = true;
    ESP_LOGI(TAG, "mypost: 就绪 · 已存 %d/%d · 区 @ assets+0x%X", cnt, MYPOST_MAX, (unsigned)s_mp_off);
}

/* ★2026-10-26 方案第 4 步：`mypost_migrate_slots` 全工程零调用 → 删除。
   它本来就是为了「旧卡槽搬到新槽」，但实测旧区整体落在新区后半段（槽 k → 槽 k+101），
   老卡数据自动在位，再搬一次反而会把同一张卡复制成两张（见 mypost_init 上方注释）。
   ⇒ 这个函数不只是没用，是**不该用**。 */

int mypost_count(void)
{
    int c = 0;
    for (int k = 0; k < MYPOST_MAX; ++k) if (s_mp_ts[k]) c++;
    return c;
}

