/* ══════════════════════════════════════════════════════════════════════════════
 * ui_asset.h —— UI 页面容器（'UIRL'）读取层（C1 第四步第一片；2026-11-11 从 main.c 搬出）
 * ------------------------------------------------------------------------------
 * ui_touch.bin / ui.bin 是「52 页 × 语言数」的 RLE 容器。开机只把偏移表读进 RAM，
 * 取页时按偏移读出那一页的压缩块（实测 ≤2057B）再解压 ⇒ 容器本体不整块进 RAM。
 *
 * 与 assets_rw 的分工：那边管「分区里哪个区域、在哪个偏移」，这边只管
 * 「UI 容器内部的页表与 RLE 解压」。
 * ⚠ 解压缓冲是**模块内静态 5000B**，返回的指针下次调用即失效（调用方立即 blit）。
 * ════════════════════════════════════════════════════════════════════════════════ */
#ifndef UI_ASSET_H
#define UI_ASSET_H

#include <stdint.h>
#include <stdbool.h>

/* 开机一次（assets_boot_check 调）：读容器头 + 偏移表并自检，异常返回 false。 */
bool ui_asset_init(void);

/* 解压第 lp 页（**语言偏移由调用方加好**）。成功返回 5000B 位图（bit=1 → 白）；
   页号越界 / 容器坏 / 解压失败 → NULL（调用方画白页，不崩）。 */
const uint8_t *ui_asset_page(int lp);

#endif /* UI_ASSET_H */
