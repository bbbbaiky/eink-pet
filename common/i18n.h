/* ============================================================================
 * ★★★ 2026-10-13 新增：**多语言（i18n）基础设施**
 * ----------------------------------------------------------------------------
 * 用户需求（原话）：
 *   「我打算做多语言版本，暂定只做一个英文本，切换页面放在设置里面，让设置翻页，
 *     右上加页码，替换窗外风景，把窗外风景放到第二页。所有文字都要替换成英文，
 *     包括明信片的文字，你要做对应翻译，如果有些英文太长你要把它变成适当简写，
 *     然后猫猫在英文版本里就改成 Mio。」
 *
 * ---------------------------------------------------------------------------
 * 【设计取舍 —— 为什么是"全字符串表"而不是"内联三元表达式"】
 *   1. 设备端 UI 文本分两类来源：
 *        ① **固件运行时画**的（main.c 的 fb_text_* 调用 + net_prov.c 的取名页）；
 *        ② **PC 端出图时烤进 ui.bin** 的（scripts/build_ui_touch.py 的 text_l/text_c）。
 *      ①类改语言只能改固件；②类改语言必须**重跑出图脚本**（固件改不了位图里的墨）。
 *      ⇒ 两边必须共用**同一张翻译表**，否则中英切换后两套文案会打架。
 *      ★R144：以上为 10-14 的历史设计，现已作废。当前真源是
 *        `common/i18n_table_data.h`（EN/JA/ZHT 三表，共 1824 条），
 *        由 `scripts/_tools/gen_i18n_asset.py` 生成 `common/i18n_asset.bin`
 *        打进 assets 分区的 I18N 区；运行时 `t_()` 先查 app rodata 里的
 *        `post_i18n_data.h`，未命中才查 assets I18N 区。
 *        改译文流程：改三表 → `gen_i18n_asset.py` → `pack_assets.py --write`。
 *        ⚠ 本文件是头文件，**永远不要 #include i18n_table_data.h 进 .c**（会重新引入 rodata 膨胀）。
 *
 *   2. 键名 = **中文原文本身**（`T("设置")`）。
 *      理由：① 中文原文在代码里到处都是，直接当键 = 改动量最小、最不容易漏翻；
 *            ② 运行时若查不到键，**回退返回键本身（中文）** → 永远不会出现空白页；
 *            ③ 生成器可以反查"哪些中文还没进表"，做覆盖率检查。
 *
 *   3. 落地方式：`const char *t_(const char *zh)`。
 *      中文态**零查表**（直接返回入参）→ 中文版性能/行为与改动前**逐字节等价**，
 *      这才敢把全站 700+ 处文案接过来。
 *
 * ---------------------------------------------------------------------------
 * 【新增文案怎么加】
 *   ① 往 `scripts/_i18n_strings.py` 的 ZH2EN 里加 `'中文': 'English'`；
 *   ② 重跑 `python scripts/_tools/gen_i18n.py`（会同时刷新本文件与出图侧 dict）；
 *   ③ 出图侧：`from _i18n_strings import L`，把字面量换成 `L('中文')`。
 *   语言态由环境变量 `PET_LANG=zh|en` 决定（出图脚本读它），固件侧读 NVS。
 * ==========================================================================*/
#pragma once

#include <stdbool.h>
#include <stddef.h>

/* 语言枚举。★ 顺序即持久化编码（NVS petns:lang = u8），**别改已有值**。
   ★★ LANG_JA（2026-10-13 追加）/ LANG_ZHT（2026-10-14 追加）都只能**追加在末尾**
     再改 LANG_N：老设备的 NVS 里已经躺着 0/1/2，改已有值会让老用户开机跳语言。
   ★ 显示顺序 ≠ 枚举值：语言列表页要「繁體中文」紧跟「简体中文」（用户 2026-10-14
     要求），而枚举值受 NVS 兼容约束不能插队 ⇒ 列表页用 LANG_ROW2LANG[] 映射
     （行下标 → lang_t），见 main.c 语言页一节。 */
typedef enum {
    LANG_ZH = 0,      /* 简体中文（缺省） */
    LANG_EN = 1,      /* English */
    LANG_JA = 2,      /* 日本語（第三语言） */
    LANG_ZHT = 3,     /* 繁體中文（第四语言 · 2026-10-14） */
    LANG_N  = 4,
} lang_t;

/* 当前语言（定义在 main.c；触屏/按键共用）。 */
extern lang_t g_lang;

/* 查表：zh = 中文原文（键）。中文态直接返回 zh（零查表）；
   英/日/繁体态按 g_lang 在 assets 分区的 I18N 区域（开机读进 PSRAM）二分查表，
   查不到**回退 zh**（永不空白）。
   ★ 三语**共键**（键都是中文原文），所以四语复用同一份二分逻辑。
   ★ 2026-10-20：翻译表数据已移出固件 rodata（省 ~113 KB），改放 assets I18N 区域
     （common/i18n_asset.bin，由 scripts/_tools/gen_i18n_asset.py 生成）；
     改翻译流程见 i18n_table.h 顶部说明。
   zh 为 NULL 时返回 NULL —— 调用方（如 PAGE_HINT[]）有大量 NULL 表示"本页不画提示"。 */
const char *t_(const char *zh);

/* 语言名（**自称，不翻译**）：语言列表里每项都用本语言写自己的名字
   （"中文" / "English" / "日本語"），否则切到看不懂的语言就再也切不回来了。
   日志与语言选择页共用，保证两处口径一致。 */
const char *lang_name(lang_t l);

/* 便捷宏：T("设置") —— 语义化用，展开与 t_() 完全一致。 */
#define T(zh) t_(zh)
